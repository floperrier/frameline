#!/usr/bin/env bash
# Les textes que le proxy et les sessions produisent réellement, passés à scripts/trace.
cd "$(dirname "$0")" || exit 1
fail=0
strips() { # strips <cas> <texte> <attendu>
  [ "$(printf '%b' "$2" | ./trace strip)" = "$(printf '%b' "$3")" ] || { echo "ÉCHEC strip : $1"; fail=1; }
}
flags() { # flags <cas> <oui|non> <texte>
  if printf '%b' "$3" | ./trace strip | ./trace check 2> /dev/null; then got=non; else got=oui; fi
  [ "$got" = "$2" ] || { echo "ÉCHEC check : $1 (trace : $got)"; fail=1; }
}
strips 'ancien pied' 'Closes #2\n\nCorps.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n' 'Closes #2\n\nCorps.'
strips 'pied avec lien de session' 'Closes #2\n\nCorps.\n\n_Generated by [Claude Code](https://claude.ai/code/session_01AbC)_' 'Closes #2\n\nCorps.'
strips 'sans pied' 'Closes #2\n\nCorps.' 'Closes #2\n\nCorps.'
flags 'pied avec lien de session' non 'Corps.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01AbC)_'
flags 'lien de session au milieu' oui 'Voir https://claude.ai/code/session_01AbC.\n\n_Generated by [Claude Code](https://claude.ai/code)_'
flags 'co-auteur' oui 'feat: x\n\nCo-authored-by: Claude <noreply@anthropic.com>'
flags 'texte propre' non 'feat: x\n\nCorps sans trace.'
[ "$fail" = 0 ] && echo 'scripts/trace : ok'
exit "$fail"
